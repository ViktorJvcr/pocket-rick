#pragma once
#include <Arduino.h>

// ============================================================================
//  Orientation — определение ориентации робота по гравитации (BMI160)
//  Настраиваемые параметры (калибровка осей — см. инструкцию):
// ============================================================================

// Ось акселерометра, смотрящая ВВЕРХ, когда робот стоит нормально: 0 = X, 1 = Y, 2 = Z
#define ORI_UP_AXIS   1
// Знак этой оси в нормальном положении (+1.0f или -1.0f)
#define ORI_UP_SIGN   (1.0f)

// Ось, направленная ВПРАВО по экрану (для бокового смещения лужи): 0 = X, 1 = Y, 2 = Z
#define ORI_SIDE_AXIS 0
#define ORI_SIDE_SIGN (-1.0f)

// 1 — модуль сам читает BMI160 по I2C; 0 — данные подаются извне через feedRaw()
#define ORI_INTERNAL_I2C_READ 1

#define ORI_SAMPLE_MS   10        // период опроса акселерометра (100 Гц)
#define ORI_LPF_ALPHA   0.07f     // коэффициент фильтра низких частот (меньше = плавнее)
#define ORI_DOWN_ENTER  (-0.60f)  // cos угла: вход в состояние «вверх ногами» (угол > 127°)
#define ORI_DOWN_EXIT   (-0.30f)  // cos угла: выход из состояния (угол < 107°) — гистерезис

namespace Orientation {
    // Вызывать в setup() ПОСЛЕ ImuSensor::init() (I2C уже инициализирован)
    void init();

    // Вызывать каждый проход loop()
    void update();

    // Альтернативный ввод: передать сырое ускорение из TapDetector/ImuSensor
    void feedRaw(float ax, float ay, float az);

    bool  isReady();          // датчик найден и есть отфильтрованные данные
    bool  isUpsideDown();     // робот перевёрнут вверх ногами (с гистерезисом)
    uint32_t getUpsideDownMs(); // сколько мс непрерывно перевёрнут (0, если нет)

    float getUpDot();         // косинус угла к нормальному верху: +1 норма, -1 вверх ногами
    float getSideTilt();      // -1..+1: боковой крен (+1 — правый край экрана ниже)
    void  getGravity(float &gx, float &gy, float &gz); // нормализованный вектор гравитации
}
